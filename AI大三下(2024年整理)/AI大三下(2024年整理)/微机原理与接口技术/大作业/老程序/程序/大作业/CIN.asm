DATAS SEGMENT
    DATA DB 5 DUP(00H)  
DATAS ENDS

STACKS SEGMENT
    ;此处输入堆栈段代码
STACKS ENDS

CODES SEGMENT
    ASSUME CS:CODES,DS:DATAS,SS:STACKS
START:
    MOV AX,DATAS
    MOV DS,AX
    
    MOV CX,4
    MOV SI,4
AGAIN:
    CALL CIN
    MOV BYTE PTR DATA[SI],DL
    DEC SI
    LOOP AGAIN
    
    MOV AH,4CH
    INT 21H
    
CIN PROC
    PUSH AX
    PUSH BX
    
    MOV AL,0
    MOV DH,10
    MOV DL,0

IN_AGAIN:
    
    MOV AH,1
    INT 21H
    SUB AL,30H
    
    CMP AL,0
    JB IN_END
    CMP AL,9
    JA IN_END
    
    MOV BL,AL
    XCHG AL,DL
    MUL DH
    ADD AL,DL
    MOV DL,AL
    MOV AL,BL
    JMP IN_AGAIN
    
IN_END:
    POP BX
    POP AX
    RET
    ENDP

CODES ENDS
    END START