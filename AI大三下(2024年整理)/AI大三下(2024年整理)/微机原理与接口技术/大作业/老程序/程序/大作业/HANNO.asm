    ASSUME CS:CODES,DS:DATAS,SS:STACKS
START:
    MOV AX,DATAS
    MOV DS,AX
    
    MOV DH,5
  
    MOV BH,'A'
    MOV BL,'B'
    MOV CL,'C'
    CALL HANNO
    
    MOV AH,4CH
    INT 21H
HANNO PROC
    ;PUSHA
    CMP DH,1
    JE ENDD1
    
    DEC DH
    XCHG BL,CL
    PUSHA
    CALL HANNO
    POPA
    
    XCHG BL,CL
    JMP PRINT
    
MOVE2:

    XCHG BH,CL
    PUSHA
    CALL HANNO
    POPA
    JMP ENDD
    
PRINT:
    MOV DL,BH 
    MOV AH,2
    INT 21H
    MOV DL,'-'
    MOV AH,2
    INT 21H
    MOV DL,'>'
    MOV AH,2
    INT 21H
    MOV DL,BL
    MOV AH,2
    INT 21H
    MOV DL,0DH
    MOV AH,2
    INT 21H
    MOV DL,0AH
    MOV AH,2
    INT 21H
    JMP MOVE2
    
ENDD1:
    MOV DL,BH 
    MOV AH,2
    INT 21H
    MOV DL,'-'
    MOV AH,2
    INT 21H
    MOV DL,'>'
    MOV AH,2
    INT 21H
    MOV DL,BL
    MOV AH,2
    INT 21H
    MOV DL,0DH
    MOV AH,2
    INT 21H
    MOV DL,0AH
    MOV AH,2
    INT 21H
ENDD:

    ;POPA
    RET
HANNO ENDP
CODES ENDS
    END START