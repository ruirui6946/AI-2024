D_SEG SEGMENT
    LEN EQU 22H
    X DW LEN DUP (?)
    Y DW LEN DUP (?)  
D_SEG ENDS 

E_SEG SEGMENT
    R DW LEN DUP (?) 
E_SEG ENDS

STACKS SEGMENT
    ;此处输入堆栈段代码
STACKS ENDS

CODES SEGMENT
    ASSUME CS:CODES,DS:D_SEG,SS:STACKS
START:

ADDD MACRO V1
    ADD AX,V1
ENDM

    MOV AX,D_SEG
    MOV DS,AX
    MOV AX,E_SEG
    MOV ES,AX
    
    ;LOCAL CONT
    ADDD 11H,02H
    
    CALL COMPUTE
    
    MOV AH,4CH
    INT 21H
    
COMPUTE PROC
    ;LOCAL CONT
    PUSHA
    MOV DI,0
    
    MOV CX,LEN
AGAIN:
    MOV AX,WORD PTR DS:X[DI]
    ADD AX,WORD PTR DS:Y[DI]
    SUB AX,3
    MOV WORD PTR ES:R[DI],AX
    ADD DI,2
    LOOP AGAIN
    
    POPA
    RET
COMPUTE ENDP

CODES ENDS
    END START