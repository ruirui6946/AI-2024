DATAS SEGMENT
    DATA1 DB 'ABCDAbcdA01AAA23A$'
    LEN EQU $-DATA-1  
DATAS ENDS

STACKS SEGMENT
    ;此处输入堆栈段代码
STACKS ENDS

CODES SEGMENT
    ASSUME CS:CODES,DS:DATAS,SS:STACKS
START:
    MOV AX,DATAS
    MOV DS,AX
    MOV ES,AX
    
    LEA AX,DATA1
    MOV DI,AX
    
    MOV BX,0
    MOV AX,'A'
    MOV CX,LEN
SCA:
    DEC CX
    SCASB
    JNE NOTBX
    INC BX
NOTBX:
    JCXZ NEXT
    JMP SCA
NEXT:
    
    MOV AH,4CH
    INT 21H
CODES ENDS
    END START