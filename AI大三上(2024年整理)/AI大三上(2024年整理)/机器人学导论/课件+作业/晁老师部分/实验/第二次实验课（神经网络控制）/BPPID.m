close all;

% 设置学习率、惯性项和网络结构参数
xite = 0.05;% 冲量
alfa = 0.01;% 学习率
IN = 4;
H = 10;

Out = 3;

upper_bound = 0.5;
lower_bound = -0.5;

% 初始化输入到隐藏层的权重矩阵和输出层的权重矩阵
% wi = [ 0.4634 -0.4173  0.3190  0.0
%        0.1839  0.3021  0.1112  0.0
%       -0.3182  0.0470  0.0850 -0.00
%       -0.6266  0.0846  0.3751 -0.6900
%       -0.3224  0.1440 -0.2873 -0.0193
%       -0.0232 -0.0992  0.2636  0.2011
%       -0.4502 -0.2928  0.0062 -0.5640
%       -0.1975 -0.1332  0.1981  0.0422
%        0.0521  0.0673 -0.5546 -0.4830
%       -0.6016 -0.4097  0.0338 -0.1503
%     ];
wi = [
    -0.0852888573389957	0.000253057003004446	0.312531732925531	-0.159499887058704
    -0.130942172108626	-0.0152950825831614	-0.0122034754701159	0.365904558667291
    0.404744923630016	0.469302500027405	0.386496020957230	0.256258266291791
    -0.0886423440346995	-0.382271570941441	0.00316049031212739	0.455760712803700
    -0.331871205728564	-0.210516192756304	0.0184579911005753	0.451946440514327
    0.0242503050746756	-0.0461920653909089	-0.00291862113686861	-0.373085389837674
    0.317786087283270	0.0703474682330038	-0.292177819098093	-0.135197948391224
    -0.107483175684636	0.382183438501428	-0.410793861245098	0.469308165126654
    0.280575789328982	0.00528310152054737	-0.383914405182408	0.197815340001006
    0.201270007347419	-0.0182955776941348	0.417470817757304	0.479859752842609
];
% wi = lower_bound + (upper_bound - lower_bound) * rand(H, 4);
wi_1 = wi; wi_2 = wi; wi_3 = wi;
wo = [
    -0.167954574684851	-0.221224626343642	-0.509685543572882
    -0.636091904932626	-0.640007524599872	0.229681460162353
    -0.0273046356868542	-0.0413635310772897	-0.554808194031124
    -0.419089617010515	0.307790208075708	-0.297624878873010
    -0.122751017345016	-0.554738456572048	-0.0567644123341584
    0.0748069812355894	-0.614594416741501	-0.0650033416430570
    -0.0427691889767144	0.236050131204102	0.0174967840628536
