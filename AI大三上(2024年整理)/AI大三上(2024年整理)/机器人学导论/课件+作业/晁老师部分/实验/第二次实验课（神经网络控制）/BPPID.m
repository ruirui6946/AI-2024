% wo = [-0.1620  0.3674  0.1959
%       -0.0337 -0.1563 -0.1454
%        0.0898  0.7239  0.7605
%        0.3349  0.7683  0.4714
%        0.0215  0.5896  0.7143
%       -0.0914  0.4666  0.0771
%        0.4270  0.2436  0.7026
%        0.0215  0.4400  0.1121
%        0.2566  0.2486  0.4857
%        0.0198  0.4970  0.6450
%     ];
% wo = lower_bound + (upper_bound - lower_bound) * rand(H, 3);
wo_1 = wo; wo_2 = wo; wo_3 = wo;

% 初始化变量
x = [0, 0, 0];
u_1 = 0; u_2 = 0; u_3 = 0; u_4 = 0; u_5 = 0;
y_1 = 0; y_2 = 0; y_3 = 0;

Oh = zeros(H, 1);
I = Oh;
error_2 = 0;
error_1 = 0;

ts = 0.01;% time step
for k = 1:1:600
    time(k) = k * ts;
%     rin(k) = 1;% reference input
    % 参考输入（这里使用的是步进输入）
    % 如果需要使用正弦输入，取消下一行的注释
    rin(k) = sin(2 * pi * time(k));

    a(k) = 1.2 * (1 - 0.8 * exp(-0.1 * k));
    yout(k) = a(k) * y_1 / (1 + y_1^2) + u_1;% y_out实际输出
    error(k) = rin(k) - yout(k);% 参考输入（希望的输出）与实际输出的的差
    xi = [rin(k), yout(k), error(k), 1];% 神经网络输入

    % 计算误差历史
    x(1) = error(k) - error_1;
    x(2) = error(k);
    x(3) = error(k) - 2 * error_1 + error_2;
    epid = [x(1); x(2); x(3)];

    % 计算中间层的输入
    I = xi * wi';

    % 中间层的激活函数
    for j = 1:1:H
        Oh(j) = (exp(I(j)) - exp(-I(j))) / (exp(I(j)) + exp(-I(j)));
    end

    % 计算输出层的输入
    K = wo' * Oh;

    % 输出层的激活函数
    for l = 1:1:Out
        K(l) = exp(K(l)) / (exp(K(l)) + exp(-K(l)));
    end

    % 获取PID参数
    kp(k) = K(1); ki(k) = K(2); kd(k) = K(3);
    Kpid = [kp(k), ki(k), kd(k)];

    % 计算控制器输出增量
    du(k) = Kpid * epid;
    u(k) = u_1 + du(k);

    % 限制控制器输出
    if u(k) >= 10
        u(k) = 10;
    end
    if u(k) <= -10
        u(k) = -10;
    end

    % 开始反向传播
    % 计算误差灵敏度
    dyu(k) = sign((yout(k) - y_1) / (u(k) - u_1 + 0.0000001));

    % 计算输出层的误差项
    for j = 1:1:Out
        dK(j) = 2 / (exp(K(j)) + exp(-K(j)))^2;
    end

    for l = 1:1:Out
        delta3(l) = error(k) * dyu(k) * epid(l) * dK(l);
    end

    % 更新输出层权重
    for l = 1:1:Out
        for i = 1:1:H
            d_wo = xite * delta3(l) * Oh(i) + alfa * (wo_1 - wo_2);
        end
    end
    wo = wo_1 + d_wo + alfa * (wo_1 - wo_2);

    % 计算中间层的误差项
    for i = 1:1:H
        dO(i) = 4 / (exp(I(i)) + exp(-I(i)))^2;
    end

    segma = delta3 * wo';
    for i = 1:1:H
        delta2(i) = dO(i) * segma(i);
    end

    % 更新输入到隐藏层的权重
    d_wi = xite * delta2' * xi + alfa * (wi_1 - wi_2);
    wi = wi_1 + d_wi;

    % 更新历史参数
    u_5 = u_4; u_4 = u_3; u_3 = u_2; u_2 = u_1; u_1 = u(k);
    y_2 = y_1; y_1 = yout(k);
    wo_3 = wo_2; wo_2 = wo_1; wo_1 = wo;
    wi_3 = wi_2; wi_2 = wi_1; wi_1 = wi;
    error_2 = error_1;
    error_1 = error(k);
end

